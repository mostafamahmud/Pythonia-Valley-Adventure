# --- الكود التطبيقي ---
hours = [1, 2, 3, 4]
tower_power = [15, 25, 35, 45]  # نلاحظ أن الطاقة تزيد بمقدار ثابت (+10 كل ساعة)

# حساب معدل التغير (الميل)
growth_rate = (tower_power[-1] - tower_power[0]) / (hours[-1] - hours[0])

# التنبؤ بالساعة الخامسة
next_hour = 5
predicted_power = tower_power[-1] + growth_rate * (next_hour - hours[-1])

print(f"معدل النمو كل ساعة: +{growth_rate}")
print(f"التنبؤ بطاقة البرج في الساعة {next_hour}: {predicted_power}")

